class Command(BaseCommand):
    help = "Publish the three newsroom stories supplied on 22 September 2026."

    def add_arguments(self, parser):
        parser.add_argument("--hanuman-image", type=Path)

    def handle(self, *args, **options):
        User = get_user_model()
        author = User.objects.filter(is_superuser=True).first() or User.objects.filter(is_staff=True).first() or User.objects.first()
        if author is None:
            raise CommandError("Create an editor/admin user before publishing articles.")

        image_path = options.get("hanuman_image")
        if image_path:
            image_path = image_path.expanduser().resolve()
            if not image_path.is_file():
                raise CommandError(f"Image not found: {image_path}")

        for index, story in enumerate(STORIES):
            name, hindi_name, slug = story["category"]
            category, _ = Category.objects.get_or_create(
                slug=slug,
                defaults={"name": name, "hindi_name": hindi_name, "active": True},
            )
            article, _ = Article.objects.update_or_create(
                title=story["title"],
                defaults={
                    "summary": story["summary"],
                    "body": story["body"],
                    "category": category,
                    "author": author,
                    "status": Article.Status.PUBLISHED,
                    "published_at": timezone.now() - timezone.timedelta(minutes=index),
                    "is_breaking": True,
                    "is_top_story": True,
                    "is_homepage_hero": index == 2,
                    "is_featured": True,
                    "is_trending": True,
                    "is_editor_pick": True,
                },
            )
            if story.get("image") and image_path:
                article.featured_image.save(
                    "hanuman-ansh-satvik-sharma.jpg",
                    ContentFile(image_path.read_bytes()),
                    save=True,
                )
            self.stdout.write(f"Published article {article.pk}")
