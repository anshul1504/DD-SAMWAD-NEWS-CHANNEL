def repair_text(text, index):
    text = strip_tags(text).replace("\u00ad", " ").replace("\u200b", " ")
    if index == 31 and "बगलामुखी" in text:
        text = text[text.index("बगलामुखी") - 4:]
    if index == 30 and "पितृ पक्ष" in text:
        text = text[text.index("पितृ पक्ष"):]
    for wrong, right in REPLACEMENTS.items():
        text = text.replace(wrong, right)
    text = re.sub(r"[ʏʕȂȆ¼ʎǲʖʏ¯§Èö´]", "", text)
    text = re.sub(r"\s+", " ", text).strip()
    # Strip any remaining print colophon that accidentally precedes the story.
    for marker in ("गोयल ग्रीन कॉलोनी", "गोयल ग्ीन कॉलोनी", "संपादक : असीत पाठक"):
        if text.startswith(marker):
            cut = max(text.find("बगलामुखी"), text.find("पितृ पक्ष"))
            if cut > 0:
                text = text[cut:]
    return text


class Command(BaseCommand):
    help = "Clean summaries, print-footer contamination and OCR layout in issue 03."

    def handle(self, *args, **options):
        articles = list(Article.objects.filter(published_at__date=ISSUE_DATE).order_by("published_at", "id"))
        if len(articles) != 32:
            raise CommandError(f"Expected 32 articles, found {len(articles)}")
        for index, article in enumerate(articles):
            article.summary = SUMMARIES[index]
            if index != 26:  # This article was already manually copy-edited.
                text = repair_text(article.body, index)
                sentences = re.split(r"(?<=[।!?])\s+", text)
                paragraphs, current = [], []
                for sentence in sentences:
                    if not sentence.strip():
                        continue
                    current.append(sentence.strip())
                    if len(" ".join(current)) >= 380:
                        paragraphs.append(" ".join(current)); current = []
                if current:
                    paragraphs.append(" ".join(current))
                article.body = "".join(f"<p>{part}</p>" for part in paragraphs)
            article.save(update_fields=["summary", "body", "reading_time", "updated_at"])
        self.stdout.write(self.style.SUCCESS("Cleaned summaries and body layout for 32 issue articles."))
